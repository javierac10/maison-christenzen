/* --- Validation --- */
const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function fieldProxy(name) {
  return {
    fullName: document.getElementById("order-fullName"),
    email: document.getElementById("order-email"),
    shippingCountry: document.getElementById("order-country"),
    size: document.getElementById("order-size"),
    privacyConsent: document.getElementById("order-consent")
  }[name];
}

function setError(name, message) {
  const field = fieldProxy(name);
  const wrap = field.closest(".order-field");
  const err = wrap.querySelector(".order-error");
  if (message) {
    wrap.classList.add("invalid");
    err.textContent = message;
    err.hidden = false;
  } else {
    wrap.classList.remove("invalid");
    err.textContent = "";
    err.hidden = true;
  }
}

function validateField(name) {
  const value = fieldProxy(name).value;
  let error = "";
  switch (name) {
    case "fullName":
      if (!value.trim()) error = t("errorRequired");
      break;
    case "email":
      if (!value.trim()) error = t("errorRequired");
      else if (!emailPattern.test(value.trim())) error = t("errorEmail");
      break;
    case "shippingCountry":
    case "size":
      if (!value) error = t("errorRequired");
      break;
    case "privacyConsent":
      if (!fieldProxy(name).checked) error = t("errorConsent");
      break;
  }
  setError(name, error);
  return !error;
}

function checkValid(name) {
  switch (name) {
    case "fullName": return !!fieldProxy(name).value.trim();
    case "email": return emailPattern.test(fieldProxy(name).value.trim());
    case "shippingCountry":
    case "size": return !!fieldProxy(name).value;
    case "privacyConsent": return fieldProxy(name).checked;
    default: return false;
  }
}

function isFormValid() {
  return ["fullName", "email", "shippingCountry", "size", "privacyConsent"].every(checkValid);
}

function refreshSubmit() {
  document.getElementById("order-submit").disabled = !isFormValid();
}

["fullName", "email", "shippingCountry", "size"].forEach(name => {
  const el = fieldProxy(name);
  const event = (el.tagName === "SELECT") ? "change" : "input";
  el.addEventListener(event, () => {
    if (name === "email") {
      const v = el.value.trim();
      if (v && !emailPattern.test(v)) setError("email", t("errorEmail"));
      else setError("email", "");
    } else {
      setError(name, "");
    }
    refreshSubmit();
  });
});

